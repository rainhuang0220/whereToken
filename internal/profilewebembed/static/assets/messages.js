(function () {
  var MESSAGES = window.WT_MESSAGES;
  var STORAGE = "wt-lang";
  function valid(v) { return v === "en" || v === "zh-CN" ? v : ""; }
  function resolve() {
    var q = "";
    try { q = new URLSearchParams(location.search).get("lang") || ""; } catch (e) {}
    if (valid(q)) return valid(q);
    try {
      var saved = localStorage.getItem(STORAGE);
      if (valid(saved)) return valid(saved);
    } catch (e2) {}
    return "en";
  }
  var lang = resolve();
  try {
    var url = new URL(location.href);
    var raw = url.searchParams.get("lang");
    if (raw && !valid(raw)) {
      url.searchParams.delete("lang");
      history.replaceState(null, "", url.pathname + url.search + url.hash);
    }
  } catch (e3) {}
  function locale() { return lang === "zh-CN" ? "zh-CN" : "en"; }
  function t(key, vars) {
    var table = MESSAGES[lang] || MESSAGES.en;
    var fallback = MESSAGES.en;
    var s = table && table[key] != null ? table[key] : (fallback[key] != null ? fallback[key] : key);
    if (vars) {
      Object.keys(vars).forEach(function (name) {
        s = s.split("{" + name + "}").join(String(vars[name]));
      });
    }
    return s;
  }
  function applyStatic() {
    document.documentElement.lang = locale();
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    document.title = t("meta.title");
    document.querySelectorAll("[data-lang-set]").forEach(function (b) {
      b.setAttribute("aria-pressed", b.getAttribute("data-lang-set") === lang ? "true" : "false");
    });
    document.documentElement.removeAttribute("data-i18n-pending");
  }
  function setLang(next, persist) {
    next = valid(next) || "en";
    lang = next;
    if (persist) {
      try { localStorage.setItem(STORAGE, next); } catch (e) {}
    }
    try {
      var url = new URL(location.href);
      url.searchParams.set("lang", next);
      history.replaceState(null, "", url.pathname + url.search + url.hash);
    } catch (e2) {}
    applyStatic();
    if (typeof window.__WT_RERENDER === "function") window.__WT_RERENDER();
  }
  window.WT_I18N = {
    t: t,
    locale: locale,
    lang: function () { return lang; },
    setLang: setLang,
    applyStatic: applyStatic,
    valid: valid
  };
  applyStatic();
})();
